// Ersetzt alle festen Texte (und Beschriftungen wie placeholder, aria-label, title) durch Englisch.
function seiteUebersetzen(wurzel = document.body) {
  if (typeof SPRACHE === "undefined" || SPRACHE !== "en") return;
  document.documentElement.lang = "en";
  const lauf = document.createTreeWalker(wurzel, NodeFilter.SHOW_TEXT);
  const knoten = [];
  while (lauf.nextNode()) knoten.push(lauf.currentNode);
  for (const k of knoten) {
    const roh = k.nodeValue, text = roh.replace(/\s+/g, " ").trim();
    if (text && ENGLISCH[text]) k.nodeValue = roh.replace(roh.trim(), ENGLISCH[text]);
  }
  wurzel.querySelectorAll("[placeholder],[aria-label],[title],[alt]").forEach((el) => {
    for (const attr of ["placeholder", "aria-label", "title", "alt"]) {
      const w = el.getAttribute(attr);
      if (w && ENGLISCH[w.trim()]) el.setAttribute(attr, ENGLISCH[w.trim()]);
    }
  });
  if (ENGLISCH[document.title]) document.title = ENGLISCH[document.title];
}
